        assert_eq!(vertaal_fout(Some("ru"), "It is not your turn"), "Сейчас не ваш ход");
        // Noors heeft drie codes, Portugees een variant.
        assert_eq!(vertaal_fout(Some("nb"), "It is not your turn"), "Det er ikke din tur");
        assert_eq!(vertaal_fout(Some("nn-no"), "It is not your turn"), "Det er ikke din tur");
