//! Serverteksten in de taal van de Speler: foutmeldingen en de zinnen van Meldingen.
//!
//! De bron is het Engels: een `Fout` draagt de Engelse zin, en elke taal heeft een tabel van
//! Engelse zin naar vertaling. Een taal erbij is één tabel in dit bestand en één regel in
//! [`teksten`]; verder verandert er niets. Ontbreekt een taal of een zin, dan blijft het Engels.
//! Wie Engels koos (`en`), krijgt altijd het Engels.

/// De zinnen van één taal.
pub struct Teksten {
    /// Foutmeldingen: Engelse zin naar vertaling.
    pub fouten: &'static [(&'static str, &'static str)],
    /// De Melding "jij bent aan de beurt"; `{tegen}` wordt de namen van de tegenstanders.
    pub beurt: &'static str,
    /// Het voegwoord tussen de laatste twee namen ("Ann, Bob and Cas").
    pub en: &'static str,
    /// De Melding "Vriendverzoek" (taak 162); `{naam}` wordt de Spelersnaam van de aanvrager.
    pub vriendverzoek: &'static str,
    /// De Melding "Uitdaging" (taak 163); `{naam}` wordt de Spelersnaam van de uitdager.
    pub uitdaging: &'static str,
}

